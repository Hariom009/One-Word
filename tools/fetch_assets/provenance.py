#!/usr/bin/env python3
"""Write the sources table for a book's installed media.

Same shape as Docs/06_Misc/PICTURES_IMAGE_SOURCES.md, which is the reason a licence
question about the Picture Book takes a minute to answer instead of a week. A book
whose media ships without one of these is not finished.

    python3 -I provenance.py pets image
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
BOOK_NAMES = {"pets": "Cats & Dogs", "emotions": "Emotions", "startup": "Corporate Slang"}

def main():
    book = sys.argv[1]
    kind = sys.argv[2] if len(sys.argv) > 2 else "image"
    name = BOOK_NAMES.get(book, book)
    def load(name):
        path = os.path.join(HERE, name)
        return json.load(open(path)) if os.path.exists(path) else {}
    sourced = load(f"installed-{book}.json")      # found on Commons, licence verified
    made = load(f"generated-{book}.json")         # made for us, nothing to licence
    installed = {**sourced, **made}
    entries = json.load(open(os.path.join(ROOT, "OneWord", "Shared", f"{book}.json")))
    missing = [w["term"] for w in entries if not w.get(kind)]

    out = [f"# {name} — {kind} sources", "",
           "Generated by `tools/fetch_assets/provenance.py` — edit the pipeline, not this file.", ""]
    if sourced:
        out += [f"**Sourced files** come from Wikimedia Commons and carry a **CC0** or",
                "**public-domain** mark there. Checked twice: the Commons licence category on",
                "the search, then the file's own `LicenseShortName` at install. Neither needs",
                "attribution; the author is kept as a courtesy and so a file can be traced back.", ""]
    if made:
        out += ["**Made files** were generated for this app, so there is no third-party licence",
                "and nobody to credit. What is recorded instead is the model and the date. This",
                "satisfies `Docs/06_Misc/VISUAL_ELEMENTS_PROMPT.md` §2 — every asset is made by",
                "us, code-generated, or CC0 with a licence we can show — and the statement to",
                "Apple that no copyrighted material is included.", ""]
    if kind == "clip":
        out += ["Each clip is cut to 4s or less, scaled to 720p on the long edge, and stripped of",
                "its audio track: the entry's own recording is the sound.", ""]
    out += [f"{len(installed)} of {len(entries)} entries illustrated.", ""]
    out += ["| Term | File | Origin | Credit | Source |", "|---|---|---|---|---|"]
    for term in sorted(installed):
        m = installed[term]
        if "licence" in m:
            author = (m.get("artist") or "unknown").replace("|", "/")[:60]
            out.append(f"| {term} | `{m['file']}` | {m['licence']} | {author} | "
                       f"[{m['title'][5:]}]({m['descurl']}) |")
        else:
            out.append(f"| {term} | `{m['file']}` | Made for this app | {m.get('model','?')} | "
                       f"{m.get('made','?')} |")
    if missing:
        out += ["", f"## Still without a {kind}", "",
                "No freely-licensed candidate cleared the bar. The entry draws its layout",
                "without one, so this is a gap to fill, not a bug to fix.", "",
                ", ".join(f"`{t}`" for t in missing)]
    path = os.path.join(ROOT, "Docs", "06_Misc", f"{book.upper()}_{kind.upper()}_SOURCES.md")
    open(path, "w").write("\n".join(out) + "\n")
    print("written:", os.path.relpath(path, ROOT), f"({len(installed)} rows, {len(missing)} gaps)")

if __name__ == "__main__":
    main()
